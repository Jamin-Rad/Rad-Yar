export function tradingViewSymbol(value) {
  const symbol = typeof value === 'string' ? value.trim().toUpperCase() : ''
  if (symbol && !/^[A-Z0-9_]{1,25}:[A-Z0-9_][A-Z0-9_.!\/-]{0,49}$/.test(symbol)) throw Error('نماد TradingView را همراه بورس وارد کن؛ مثل NASDAQ:AAPL.')
  return symbol
}
export function tradingViewUrl(value) {
  return `https://www.tradingview.com/chart/?symbol=${encodeURIComponent(tradingViewSymbol(value))}`
}

export function tradingViewCandidates(rows, isin) {
  const candidates = new Map()
  for (const row of rows) {
    if (!row || (isin && row.isin !== isin)) continue
    const exchange = row.prefix || row.exchange
    if (typeof exchange !== 'string' || typeof row.symbol !== 'string') continue
    let symbol
    try { symbol = tradingViewSymbol(`${exchange}:${row.symbol}`) } catch { continue }
    if (candidates.has(symbol)) continue
    candidates.set(symbol, {
      symbol,
      exchange: symbol.split(':')[0],
      name: typeof row.description === 'string' ? row.description.slice(0, 160) : '',
      currency: /^[A-Z]{3}$/.test(row.currency_code || '') ? row.currency_code : '',
    })
  }
  return [...candidates.values()].sort((a, b) => Number(b.currency === 'EUR') - Number(a.currency === 'EUR'))
}
// Same cross-origin frame URL generated by TradingView's official Advanced Chart embed.
// The frame runs on TradingView's origin; no third-party script runs in our private page.
export function tradingViewEmbedUrl(value) {
  const symbol = tradingViewSymbol(value)
  if (!symbol) return ''
  const config = { autosize: true, symbol, interval: 'D', timezone: 'Europe/Berlin', theme: 'dark', style: '1', allow_symbol_change: false, calendar: false, hide_side_toolbar: false, hide_volume:false, studies:['STD;SMA','STD;RSI'], withdateranges: true, support_host: 'https://www.tradingview.com' }
  return `https://www.tradingview-widget.com/embed-widget/advanced-chart/?locale=en#${encodeURIComponent(JSON.stringify(config))}`
}
